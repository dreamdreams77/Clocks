export function getTheme(id: string): Theme {
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}

export function applyThemeVars(theme: Theme, night: boolean) {
  const root = document.documentElement;
  Object.entries(theme.vars).forEach(([key, value]) => root.style.setProperty(key, value));
  root.style.setProperty('--bg-a', night ? theme.vars['--bg-night-from'] : theme.vars['--bg-from']);
  root.style.setProperty('--bg-b', night ? theme.vars['--bg-night-to'] : theme.vars['--bg-to']);
}
